export const MESSAGES: Record<Lang, Record<MessageKey, string>> = { en, id };

const LANG_KEY = 'lang';
let current: Lang = 'en';
let store: StorageAdapter | undefined;

export function isLang(value: unknown): value is Lang {
  return LANGS.includes(value as Lang);
}

/** Load the saved language (default English). */
export function initLang(storage: StorageAdapter): Lang {
  store = storage;
  const saved = storage.get<string>(LANG_KEY);
  current = isLang(saved) ? saved : 'en';
  return current;
}

export function getLang(): Lang {
  return current;
}

export function setLang(lang: Lang): void {
  current = lang;
  store?.set(LANG_KEY, lang);
}

/** Translate a UI message, filling {placeholders} from vars. */
export function t(key: MessageKey, vars: Record<string, string | number> = {}, lang: Lang = current): string {
  const template = MESSAGES[lang][key] || MESSAGES.en[key];
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in vars ? String(vars[name]) : match,
  );
}

/** Pick the active language from a product text, falling back to English. */
export function loc(text: LocalizedText, lang: Lang = current): string {
  return text[lang] || text.en;
}
